//! laws-md.rs — twin of skills/render/laws-md.mjs (db READ lane, cross-db laws via ATTACH).
//! NAMES ARE CONTRACT: `lawsMd` (default). Renders laws.laws (+ law_clauses) as a markdown
//! document, grouped by kind in KIND_ORDER, hard kinds first.
use rusqlite::Connection;
use serde_json::Value;
use std::collections::HashMap;

fn truthy(v: Option<&Value>) -> bool { match v { None|Some(Value::Null)=>false, Some(Value::Bool(b))=>*b, Some(Value::Number(n))=>n.as_f64().map_or(false,|f|f!=0.0&&!f.is_nan()), Some(Value::String(s))=>!s.is_empty(), Some(_)=>true } }
fn js_string(v:&Value)->String{ match v{Value::Null=>"null".into(),Value::String(s)=>s.clone(),Value::Number(n)=>n.to_string(),Value::Bool(b)=>b.to_string(),Value::Array(a)=>a.iter().map(js_string).collect::<Vec<_>>().join(","),Value::Object(_)=>"[object Object]".into()} } // = JS String(v)
fn tmpl(v: Option<&Value>) -> String { match v { None=>"undefined".into(), Some(Value::Null)=>"null".into(), Some(x)=>js_string(x) } } // = JS `${v}`
fn field<'a>(law: &'a Value, k: &str) -> Option<&'a Value> { law.get(k) }

const KIND_ORDER: [&str; 6] = ["constitutional", "constraint", "procedural", "permission", "decision", "principle"];

fn kind_header(kind: &str) -> &'static str {
    match kind {
        "constitutional" => "## \u{1f6d1} Constitutional (hard, never violated)",
        "constraint" => "## \u{2699}\u{fe0f} Constraint (hard, enforced at compile/runtime/DB layer)",
        "procedural" => "## \u{1f4cb} Procedural (workflow rules)",
        "permission" => "## \u{1f511} Permission (who-can-do-what)",
        "decision" => "## \u{1f3db}\u{fe0f} Decision (binding architectural choices)",
        "principle" => "## \u{1f4a1} Principle (soft guidelines)",
        _ => unreachable!(),
    }
}

fn escape_md(s: &str) -> String { s.replace('|', "\\|") }

fn render_law(law: &Value, clauses: &[Value]) -> String {
    let mut lines: Vec<String> = Vec::new();
    lines.push(format!("### {}", tmpl(field(law, "slug"))));
    lines.push(String::new());
    lines.push(format!("**{}**", tmpl(field(law, "title"))));
    lines.push(String::new());
    lines.push(format!("> {}", tmpl(field(law, "statement"))));
    lines.push(String::new());
    lines.push(format!("**Why:** {}", tmpl(field(law, "rationale"))));
    lines.push(String::new());

    let mut meta: Vec<String> = vec![
        format!("enforcement: `{}`", tmpl(field(law, "enforcement"))),
        format!("domain: `{}`", tmpl(field(law, "domain"))),
        format!("established_by: {}", tmpl(field(law, "established_by"))),
    ];
    if truthy(field(law, "enforcement_hook")) { meta.push(format!("hook: `{}`", tmpl(field(law, "enforcement_hook")))); }
    if truthy(field(law, "trigger_sql")) { meta.push("trigger: DB-layer".to_string()); }
    if truthy(field(law, "source_card")) { meta.push(format!("source: {}", tmpl(field(law, "source_card")))); }
    lines.push(format!("\u{2014} {}", meta.join(" \u{b7} ")));
    lines.push(String::new());

    if !clauses.is_empty() {
        let mut order: Vec<String> = Vec::new();
        let mut by_type: HashMap<String, Vec<String>> = HashMap::new();
        for c in clauses {
            let ct = js_string(c.get("clause_type").unwrap_or(&Value::Null));
            if !by_type.contains_key(&ct) { order.push(ct.clone()); by_type.insert(ct.clone(), Vec::new()); }
            by_type.get_mut(&ct).unwrap().push(js_string(c.get("text").unwrap_or(&Value::Null)));
        }
        for ct in &order {
            lines.push(format!("*{}:*", ct));
            for t in &by_type[ct] { lines.push(format!("- {}", escape_md(t))); }
            lines.push(String::new());
        }
    }

    lines.join("\n")
}

pub fn lawsMd(input: &Value, db: &Connection) -> Result<Value, String> {
    let include_archived = truthy(input.get("includeArchived"));

    let mut sql = "SELECT * FROM laws.laws WHERE superseded_by IS NULL".to_string();
    if !include_archived { sql.push_str(" AND enforcement != 'archived'"); }
    sql.push_str(" ORDER BY kind, slug");

    let all_laws = crate::db_json::query_rows(db, &sql, &[])?.as_array().cloned().unwrap_or_default();

    let mut out: Vec<String> = Vec::new();
    out.push("# antiloki laws \u{2014} auto-rendered from laws.sqlite".to_string());
    out.push(String::new());
    out.push("> **DO NOT EDIT THIS FILE.** Generated by `system.laws.render.md`.".to_string());
    out.push("> The source of truth is `laws.sqlite`. To change a law, use".to_string());
    out.push("> `system.law.add` or `system.law.supersede`.".to_string());
    out.push(String::new());
    let kinds_seen: std::collections::HashSet<String> = all_laws.iter().map(|l| js_string(l.get("kind").unwrap_or(&Value::Null))).collect();
    out.push(format!("Total: {} active laws across {} kinds.", all_laws.len(), kinds_seen.len()));
    out.push(String::new());

    for kind in KIND_ORDER {
        let laws_of_kind: Vec<&Value> = all_laws.iter().filter(|l| l.get("kind").and_then(|v| v.as_str()) == Some(kind)).collect();
        if laws_of_kind.is_empty() { continue; }
        out.push(kind_header(kind).to_string());
        out.push(String::new());
        for law in laws_of_kind {
            let law_id = law.get("id").cloned().unwrap_or(Value::Null);
            let clauses = crate::db_json::query_rows(db, "SELECT clause_type, text, order_index FROM laws.law_clauses WHERE law_id = ? ORDER BY order_index", &[law_id])?
                .as_array().cloned().unwrap_or_default();
            out.push(render_law(law, &clauses));
        }
    }

    Ok(Value::String(out.join("\n")))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn db() -> Connection {
        let c = Connection::open_in_memory().unwrap();
        c.execute_batch("ATTACH ':memory:' AS laws; \
          CREATE TABLE laws.laws (id INTEGER PRIMARY KEY, slug TEXT, kind TEXT, domain TEXT, title TEXT, statement TEXT, rationale TEXT, enforcement TEXT, enforcement_hook TEXT, trigger_sql TEXT, established_at TEXT, established_by TEXT, source_card TEXT, source_event INTEGER, source_memory INTEGER, superseded_by INTEGER, superseded_at TEXT); \
          CREATE TABLE laws.law_clauses (id INTEGER PRIMARY KEY, law_id INTEGER, clause_type TEXT, text TEXT, order_index INTEGER); \
          INSERT INTO laws.laws (id,slug,kind,domain,title,statement,rationale,enforcement,enforcement_hook,trigger_sql,established_by,source_card,superseded_by) VALUES \
            (1,'NEVER_BYPASS_WITH_AUDIT','constitutional','audit','All mutations via with-audit','Direct writes are forbidden','No audit trail otherwise','hard','law-hook-mutation-via-with-audit',NULL,'human:dani','GAP-CARD-UPDATE-ACTION',NULL), \
            (2,'ASK_BEFORE_DESTRUCTIVE','procedural','security','Confirm destructive ops','Ask before rm -rf','Reversibility matters','soft',NULL,NULL,'system:bootstrap',NULL,NULL), \
            (3,'OLD_RULE','decision','audit','Old rule','Was replaced','Old why','soft',NULL,NULL,'human:dani',NULL,99), \
            (4,'ANCIENT_RULE','decision','audit','Archived rule','Kept for history','Ancient why','archived',NULL,NULL,'human:dani',NULL,NULL); \
          INSERT INTO laws.law_clauses (id,law_id,clause_type,text,order_index) VALUES \
            (1,1,'antipattern','direct UPDATE on cards',1), \
            (2,1,'antipattern','a | pipe in text',2), \
            (3,1,'example','call card-update instead',1);").unwrap();
        c
    }

    #[test]
    fn renders_grouped_by_kind_hard_first() {
        let c = db();
        let md = lawsMd(&json!({}), &c).unwrap();
        let s = md.as_str().unwrap();
        assert!(s.starts_with("# antiloki laws \u{2014} auto-rendered from laws.sqlite"));
        assert!(s.contains("DO NOT EDIT THIS FILE"));
        // superseded_by excluded (OLD_RULE has superseded_by=99); archived excluded by default
        assert!(!s.contains("OLD_RULE"));
        assert!(!s.contains("ANCIENT_RULE"));
        assert!(s.contains("Total: 2 active laws across 2 kinds."));
        // constitutional header (hard) appears before procedural
        let ci = s.find("Constitutional").unwrap();
        let pi = s.find("Procedural").unwrap();
        assert!(ci < pi);
        assert!(s.contains("### NEVER_BYPASS_WITH_AUDIT"));
        assert!(s.contains("**All mutations via with-audit**"));
        assert!(s.contains("> Direct writes are forbidden"));
        assert!(s.contains("**Why:** No audit trail otherwise"));
        assert!(s.contains("enforcement: `hard` \u{b7} domain: `audit` \u{b7} established_by: human:dani \u{b7} hook: `law-hook-mutation-via-with-audit` \u{b7} source: GAP-CARD-UPDATE-ACTION"));
        // clause grouping: antipattern (2 items, pipe escaped) then example
        assert!(s.contains("*antipattern:*\n- direct UPDATE on cards\n- a \\| pipe in text\n\n*example:*\n- call card-update instead"));
        // law with no hook/trigger/source: meta line has only the 3 base fields
        assert!(s.contains("enforcement: `soft` \u{b7} domain: `security` \u{b7} established_by: system:bootstrap\n"));
    }

    #[test]
    fn include_archived_flag_includes_archived_laws() {
        let c = db();
        let md = lawsMd(&json!({ "includeArchived": true }), &c).unwrap();
        let s = md.as_str().unwrap();
        assert!(s.contains("ANCIENT_RULE"));
        assert!(!s.contains("OLD_RULE")); // superseded_by still excludes regardless of includeArchived
        // includeArchived=true admits ANCIENT_RULE (kind=decision) alongside NEVER_BYPASS_WITH_AUDIT
        // (constitutional) and ASK_BEFORE_DESTRUCTIVE (procedural) — 3 laws, 3 DISTINCT kinds, not 2
        // (decision doesn't share a kind with either of the other two active laws).
        assert!(s.contains("Total: 3 active laws across 3 kinds."));
    }

    #[test]
    fn law_with_no_clauses_omits_clause_sections() {
        let c = db();
        let md = lawsMd(&json!({}), &c).unwrap();
        let s = md.as_str().unwrap();
        assert!(s.contains("ASK_BEFORE_DESTRUCTIVE"));
        // no clause markers right after ASK_BEFORE_DESTRUCTIVE's meta line before the next law/end
        let idx = s.find("### ASK_BEFORE_DESTRUCTIVE").unwrap();
        assert!(!s[idx..].contains("*antipattern:*"));
    }
}
